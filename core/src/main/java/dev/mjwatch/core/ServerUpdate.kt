package dev.mjwatch.core

fun serverUpdateFailure(code:String):String=when(code) {
 "health_failed" -> "Сервер не прошёл проверку работоспособности. Результат отката тоже не подтверждён. Не запускайте обновление повторно: проверьте состояние MJWatch и TorrServer и журнал сервера."
 "update_failed_binary_rollback_confirmed" -> "Новая версия не прошла проверку. Сервер вернулся к прежней версии и подтвердил её работоспособность."
 "already_installed" -> "Выбранная версия уже установлена. Вернитесь в обслуживание, чтобы проверить текущую версию."
 "not_newer_release" -> "Выбранный пакет не новее установленной версии. Выберите более новую поставку."
 "incompatible_release", "supply_integrity" -> "Сервер отклонил пакет обновления. Выберите встроенную поставку из свежей версии приложения."
 else -> "Сервер не подтвердил обновление. Проверьте его состояние перед новой попыткой. Код ошибки доступен в подробностях."
}
